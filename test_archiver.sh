# Общее количество тестов (пройденные + проваленные)
TOTAL=$((PASSED + FAILED))
# Печатаем сводку: сколько прошло, сколько всего, сколько провалено
echo -e " ИТОГО: $PASSED прошло из $TOTAL, $FAILED провалено"
