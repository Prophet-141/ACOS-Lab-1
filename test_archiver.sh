#!/bin/bash
# Указываем, что скрипт должен выполняться интерпретатором bash

# ========== Настройки ==========
SCRIPT="./log_archiver.sh"      # путь до тестируемого скрипта
TEST_DIR="/log"                 # тестовая папка
BACKUP_DIR="/backup"            # папка для архивов
LOG_FILE="./test_results.log"   # файл с логами

# Счётчики
# Счётчик успешно пройденных тестов
PASSED=0
# Счётчик проваленных тестов
FAILED=0

# ========== Вспомогательные функции ==========

# Проверка, что log_archiver.sh существует
if [ ! -f "$SCRIPT" ]; then
    echo -e "ОШИБКА: $SCRIPT не найден в текущей директории!"
    exit 1
fi

# Функция для очистки тестовой среды перед каждым тестом
cleanup_env() {
    # Рекурсивно удаляет тестовую папку с правами root
    sudo rm -rf "$TEST_DIR"
    # Рекурсивно удаляет папку с архивами с правами root
    sudo rm -rf "$BACKUP_DIR"
    # Создаёт тестовую папку заново
    sudo mkdir -p "$TEST_DIR"
    # Создаёт папку для архивов заново
    sudo mkdir -p "$BACKUP_DIR"
    # Даём права на запись текущему пользователю
    sudo chown -R "$(whoami)":"$(whoami)" "$TEST_DIR" "$BACKUP_DIR"
}

# Печать заголовка теста
print_test_header() {
    echo ""
    echo -e "====================================================="
    echo -e " ТЕСТ: $1"
    echo -e "====================================================="
}

# Функция для фиксации успешного теста
mark_pass() {
    echo -e "[PASS] $1"
    PASSED=$((PASSED + 1))
    # Дописывает строку об успехе в файл лога
    echo "[PASS] $1" >> "$LOG_FILE"
}

# Функция для фиксации проваленного теста
mark_fail() {
    echo -e "[FAIL] $1"
    FAILED=$((FAILED + 1))
    # Дописывает строку о провале в файл лога
    echo "[FAIL] $1" >> "$LOG_FILE"
}

# ============================================================
# ТЕСТ 1: Несуществующая папка
# ============================================================

test_nonexistent_dir() {
    print_test_header "1. Несуществующая папка"
    # Очищаем тестовую среду
    cleanup_env

    # Удаляем папку /log, чтобы сымитировать отсутствие директории
    sudo rm -rf /log

    # Запускаем тестируемый скрипт с несуществующей папкой
    OUTPUT=$(sudo "$SCRIPT" /log 80 3 2>&1)
    # Сохраняем код возврата тестируемого скрипта
    EXIT_CODE=$?

    # Выводим весь вывод тестируемого скрипта в консоль
    echo "Вывод скрипта: $OUTPUT"

    # Проверяем: код возврата не 0 и в выводе есть слово "не существует" (без учёта регистра)
    if [ $EXIT_CODE -ne 0 ] && echo "$OUTPUT" | grep -qi "не существует"; then
        # Фиксируем успех теста
        mark_pass "Скрипт корректно отказался работать с несуществующей папкой"
    else
        # Фиксируем провал теста
        mark_fail "Скрипт не выдал ошибку при несуществующей папке"
    fi
}

# ============================================================
# ТЕСТ 2: Некорректный порог (150%)
# ============================================================

test_bad_threshold() {
    print_test_header "2. Порог 150%"
    # Очищаем тестовую среду
    cleanup_env
    # Создаём тестовый файл в тестовой папке
    sudo echo "test" > "$TEST_DIR/file.txt"

    # Запускаем скрипт с недопустимым порогом 150, записываем вывод
    OUTPUT=$(sudo "$SCRIPT" /log 150 3 2>&1)
    # Сохраняем код возврата скрипта
    EXIT_CODE=$?

    echo "Вывод скрипта: $OUTPUT"
    echo "Код возврата: $EXIT_CODE"

    # Проверяем, что код возврата не 0 и что в выводе есть слово "Порог" или "ОШИБКА"
    if [ $EXIT_CODE -ne 0 ] && echo "$OUTPUT" | grep -qiE "порог|ошибка"; then
        # Фиксируем успех теста
        mark_pass "Скрипт отклонил порог 150%"
    else
        # Фиксируем провал с указанием кода возврата
        mark_fail "Скрипт не отклонил порог 150% (exit=$EXIT_CODE)"
    fi
}

# ============================================================
# ТЕСТ 3: Некорректное количество файлов (0)
# ============================================================

test_bad_mfiles() {
    print_test_header "3. Kоличество файлов = 0"
    # Очищаем тестовую среду
    cleanup_env
    # Создаём тестовый файл
    sudo echo "test" > "$TEST_DIR/file.txt"

    # Запускаем скрипт с M=0, записываем вывод
    OUTPUT=$(sudo "$SCRIPT" /log 50 0 2>&1)
    # Сохраняем код возврата
    EXIT_CODE=$?

    # Выводим вывод скрипта
    echo "Вывод скрипта: $OUTPUT"

    # Проверяем: ненулевой код возврата И слово "положительным" в выводе
    if [ $EXIT_CODE -ne 0 ] && echo "$OUTPUT" | grep -qi "положительным"; then
        # Фиксируем успех
        mark_pass "Скрипт отклонил M=0"
    else
        # Фиксируем провал
